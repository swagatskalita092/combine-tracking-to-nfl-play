import sys, pandas as pd
D = sys.argv[1]
pd.set_option("display.width", 200, "display.max_columns", 60, "display.max_rows", 200)
cr = pd.read_csv(f"{D}/combine_results.csv", na_values=["NA"])
pl = pd.read_csv(f"{D}/players.csv")
ct = pd.read_csv(f"{D}/combine_tracking.csv")
pcs = pd.read_csv(f"{D}/player_career_successes.csv")
print("combine_results", cr.shape, "| players", pl.shape, "| career_succ", pcs.shape)
print("\nplayers per draft_year x combine_position"); print(pd.crosstab(cr.combine_position, cr.draft_year, margins=True))
print("\ncombine_results non-null rate by position (%)")
print((cr.groupby("combine_position").apply(lambda g: g.drop(columns=["combine_position","draft_year","nfl_id"]).notna().mean()*100)).round(0).astype(int).T)
print("\ncombine_tracking", ct.shape, "| players", ct.nfl_id.nunique(), "| entity_type", ct.entity_type.value_counts().to_dict())
print("\nsample interval (s):", ct.sort_values(["event_id","nfl_id","time"]).groupby(["event_id","nfl_id"]).time.apply(lambda s: pd.to_datetime(s).diff().dt.total_seconds().median()).median())
g = ct.groupby(["drill_type","drill_name"]).agg(rows=("x","size"), players=("nfl_id","nunique"), events=("event_id","nunique"), attempts=("attempt","nunique"))
print("\ndrills"); print(g)
print("\nplayers in tracking but not in results:", len(set(ct.nfl_id)-set(cr.nfl_id)), "| in results but no tracking:", len(set(cr.nfl_id)-set(ct.nfl_id)))
print("\nplayers positions (NFL):"); print(pl.nfl_position.value_counts().to_dict())
print("\ncareer successes describe"); print(pcs.describe().T[["count","mean","max"]])
print("\ncombine drill_type x year"); print(pd.crosstab(ct.drop_duplicates(["event_id","nfl_id"]).drill_type, ct.drop_duplicates(["event_id","nfl_id"]).draft_year))
